List<String> _keywords(String name, String nameAr, String brand) {
  final words = <String>{};
  for (final part in '$name $brand'.toLowerCase().split(
    RegExp(r'[^a-z0-9]+'),
  )) {
    if (part.length >= 2) words.add(part);
  }
  for (final part in nameAr.split(RegExp(r'\s+'))) {
    if (part.length >= 2) words.add(part);
  }
  return words.toList();
}

Product _p(
  String id,
  String categoryId,
  String subcategoryId,
  String name,
  String nameAr,
  String brand,
  double price,
  double? oldPrice,
  double rating,
  int reviewCount,
  int stock,
  String description,
  String descriptionAr,
) {
  return Product(
    id: id,
    name: name,
    nameAr: nameAr,
    brand: brand,
    categoryId: categoryId,
    subcategoryId: subcategoryId,
    price: price,
    oldPrice: oldPrice,
    rating: rating,
    reviewCount: reviewCount,
    stock: stock,
    description: description,
    descriptionAr: descriptionAr,
    keywords: _keywords(name, nameAr, brand),
  );
}

